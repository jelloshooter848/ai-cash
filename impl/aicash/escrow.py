# FundingInfo — the public (secret-free) description of a funded job
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class FundingInfo:
    """What the payer hands the payee after funding: the by-hash output
    layout.  Contains no secrets of any kind — the refund secrets stay with
    the payer, the output secrets with their holders, the rung preimages
    with the arbiters.

    ``outputs`` entries: ``{milestone, arbiter_id, rung, amount_mc,
    secret_hash, preimage_hash, expiry}``.

    Wire form (payer→payee across a process boundary): ``to_dict()``
    returns a canonical-JSON-safe dict — string keys throughout (milestone
    keys of ``expiries`` become decimal strings), hash fields already b64u
    strings, no floats anywhere — suitable for
    ``tokencodec.canonical_json``; ``from_dict()`` parses it back.
    ``EscrowPayee.verify_funding`` accepts either form.
    """

    job_id: str
    mint_id: str
    outputs: tuple
    expiries: dict
    burn_mc: int = 0
    change_mc: int = 0

    _OUTPUT_FIELDS = (
        "milestone",
        "arbiter_id",
        "rung",
        "amount_mc",
        "secret_hash",
        "preimage_hash",
        "expiry",
    )

    def to_dict(self) -> dict:
        """The canonical-JSON-safe wire form of the funding handoff.

        Exactly the keys ``job_id``, ``mint_id``, ``outputs``,
        ``expiries``, ``burn_mc``, ``change_mc``; ``expiries`` keys are
        the milestone numbers as decimal strings (canonical JSON requires
        string object keys).  Secret-free by construction — FundingInfo
        carries only public, by-hash material.
        """
        return {
            "job_id": self.job_id,
            "mint_id": self.mint_id,
            "outputs": [dict(o) for o in self.outputs],
            "expiries": {str(m): t for m, t in self.expiries.items()},
            "burn_mc": self.burn_mc,
            "change_mc": self.change_mc,
        }

    @classmethod
    def from_dict(cls, d: dict) -> "FundingInfo":
        """Parse the ``to_dict`` wire form back into a FundingInfo.

        Validates the wire shape (exact top-level keys, plain-int amounts
        and expiries, 32-byte b64u hash fields, int-or-"fee" rungs,
        decimal-string milestone keys) and raises ``EscrowError`` on any
        deviation.  The §9.3 semantic verification — signatures, ledger
        state, attested hashes — remains ``verify_funding``'s job.
        """
        if not isinstance(d, dict):
            raise EscrowError("funding wire form must be a dict")
        expected = {
            "job_id", "mint_id", "outputs", "expiries", "burn_mc", "change_mc",
        }
        if set(d) != expected:
            raise EscrowError(
                "funding wire form must have exactly the keys %s"
                % sorted(expected)
            )
        if not isinstance(d["job_id"], str) or not isinstance(d["mint_id"], str):
            raise EscrowError("job_id and mint_id must be strings")
        if not isinstance(d["outputs"], (list, tuple)):
            raise EscrowError("outputs must be a list")
        outputs = []
        for o in d["outputs"]:
            if not isinstance(o, dict) or set(o) != set(cls._OUTPUT_FIELDS):
                raise EscrowError(
                    "each output must be a dict with exactly the keys %s"
                    % (cls._OUTPUT_FIELDS,)
                )
            for name in ("milestone", "amount_mc", "expiry"):
                if type(o[name]) is not int:
                    raise EscrowError(f"output {name} must be a plain int")
            if not isinstance(o["arbiter_id"], str):
                raise EscrowError("output arbiter_id must be a string")
            if o["rung"] != FEE_RUNG and type(o["rung"]) is not int:
                raise EscrowError(
                    f'output rung must be an int or "{FEE_RUNG}"'
                )
            for name in ("secret_hash", "preimage_hash"):
                try:
                    b64u_decode(o[name], expect_len=32)
                except TokenError:
                    raise EscrowError(
                        f"output {name} must be a 32-byte b64u hash"
                    ) from None
            outputs.append(dict(o))
        if not isinstance(d["expiries"], dict):
            raise EscrowError("expiries must be a dict")
        expiries = {}
        for k, v in d["expiries"].items():
            if not isinstance(k, str) or not k.isdigit() or str(int(k)) != k:
                raise EscrowError(
                    "expiries keys must be canonical decimal strings"
                )
            if type(v) is not int:
                raise EscrowError("expiries values must be plain ints")
            expiries[int(k)] = v
        for name in ("burn_mc", "change_mc"):
            if type(d[name]) is not int or d[name] < 0:
                raise EscrowError(f"{name} must be a non-negative int")
        return cls(
            job_id=d["job_id"],
            mint_id=d["mint_id"],
            outputs=tuple(outputs),
            expiries=expiries,
            burn_mc=d["burn_mc"],
            change_mc=d["change_mc"],
        )


# ---------------------------------------------------------------------------
# Arbiter — one instance per panel member (holds its OWN preimages + key)
# ---------------------------------------------------------------------------


class Arbiter:
    """One panel member: its own rung preimages, its own fee preimages, its
    own Ed25519 signing key (C05).  Nothing here is ever shared (L15).

    Single-arbiter milestones are the ``k=1, n=1`` degenerate panel: the
    arbiter's own signed vote is the rendered decision, so even a solo
    release leaves a signed record.
    """

    def __init__(self, arbiter_id: str, keypair: tuple[bytes, bytes] | None = None):
        if not isinstance(arbiter_id, str) or not arbiter_id:
            raise EscrowError("arbiter_id must be a non-empty string")
        if keypair is None:
            keypair = generate_keypair()
        self.arbiter_id = arbiter_id
        self._private, self.public = keypair
        self.k = 1
        self.panel_pubs: dict[str, bytes] = {arbiter_id: self.public}
        self._rungs: dict[tuple, list] = {}  # (job, m) -> [(rung, amount, preimage)]
        self._fees: dict[tuple, tuple] = {}  # (job, m) -> (amount, preimage)

    def set_panel(self, k: int, panel_pubs: dict) -> None:
        """Configure the quorum rule: ``k`` signed votes out of the named
        panel members (arbiter_id → Ed25519 public key)."""
        if type(k) is not int or k < 1:
            raise EscrowError("k must be a positive integer")
        if not isinstance(panel_pubs, dict) or self.arbiter_id not in panel_pubs:
            raise EscrowError("panel_pubs must include this arbiter")
        if k > len(panel_pubs):
            raise EscrowError("k cannot exceed the panel size")
        self.k = k
        self.panel_pubs = dict(panel_pubs)

    # -- attestation -----------------------------------------------------

    def attest_rungs(
        self, job_id: str, m: int, rung_values: list[int], fee_mc: int = 0
    ) -> list[dict]:
        """Generate this arbiter's OWN rung preimages (and, when
        ``fee_mc > 0``, its decision-neutral fee preimage) for milestone
        ``m`` and return the signed attestations
        ``{job_id, milestone, rung, amount_mc, preimage_hash}`` (§9.3) —
        each hash attested by the one party that holds its preimage."""
        key = (job_id, m)
        if key in self._rungs:
            raise EscrowError("rungs for this (job, milestone) already attested")
        if type(m) is not int or m < 0:
            raise EscrowError("milestone must be a non-negative integer")
        if type(fee_mc) is not int or fee_mc < 0:
            raise EscrowError("fee_mc must be a non-negative integer")
        rungs = []
        attestations = []
        for r, value in enumerate(rung_values):
            if type(value) is not int or value <= 0:
                raise EscrowError("rung values must be positive integers")
            preimage = new_secret()
            rungs.append((r, value, preimage))
            attestations.append(self._attest(job_id, m, r, value, preimage))
        self._rungs[key] = rungs
        if fee_mc > 0:
            # The fee preimage is a FRESH independent secret — never derived
            # from or equal to any rung preimage (requirement 5).
            fee_preimage = new_secret()
            self._fees[key] = (fee_mc, fee_preimage)
            attestations.append(
                self._attest(job_id, m, FEE_RUNG, fee_mc, fee_preimage)
            )
        return attestations

    def _attest(self, job_id, m, rung, amount_mc, preimage) -> dict:
        return attach_sig(
            {
                "kind": "attestation",
                "v": SCHEMA_V,
                "job_id": job_id,
                "milestone": m,
                "arbiter_id": self.arbiter_id,
                "rung": rung,
                "amount_mc": amount_mc,
                "preimage_hash": _sha256_b64u(preimage),
            },
            self._private,
        )

    # -- voting ----------------------------------------------------------

    def vote(self, job_id: str, m: int, evidence, decision) -> dict:
        """A signed vote over the delivery evidence, bound to
        ``(job_id, milestone, evidence_hash)`` (B7).  ``decision`` is
        "release", "refund", or an exact fraction for a split award."""
        f = _as_fraction(decision)
        body = {
            "kind": "vote",
            "v": SCHEMA_V,
            "job_id": job_id,
            "milestone": m,
            "arbiter_id": self.arbiter_id,
            "evidence_hash": evidence_hash(evidence),
            "decision": "release" if f == 1 else "refund" if f == 0 else "split",
            "award_num": f.numerator,
            "award_den": f.denominator,
        }
        return attach_sig(body, self._private)

    def _count_quorum(self, job_id, m, awarded: Fraction, votes) -> int:
        """Largest set of valid signed votes for exactly this
        (job, milestone, award) from distinct panel members over ONE common
        evidence hash — votes bound to different evidence never combine."""
        by_evidence: dict[str, set] = {}
        for v in votes:
            if not isinstance(v, dict):
                continue
            aid = v.get("arbiter_id")
            pub = self.panel_pubs.get(aid)
            if pub is None:
                continue
            if v.get("job_id") != job_id or v.get("milestone") != m:
                continue
            num, den = v.get("award_num"), v.get("award_den")
            if (
                type(num) is not int
                or type(den) is not int
                or den < 1
                or Fraction(num, den) != awarded
            ):
                continue
            eh = v.get("evidence_hash")
            if not isinstance(eh, str):
                continue
            if not verify_obj(v, pub):
                continue
            by_evidence.setdefault(eh, set()).add(aid)
        return max((len(s) for s in by_evidence.values()), default=0)

    # -- reveal ----------------------------------------------------------

    def reveal(
        self,
        job_id: str,
        m: int,
        awarded_fraction,
        votes=(),
        force: bool = False,
    ) -> dict:
        """Reveal this arbiter's preimages for the awarded share of its
        rungs, plus its decision-neutral fee preimage (a decision — any
        decision — was rendered).

        Convention (requirement 3): refuses with ``QuorumNotMet`` unless
        ``votes`` contains ``k`` valid signed votes from distinct panel
        members for exactly this award over one evidence hash.
        ``force=True`` is a TEST-ONLY defection model: it skips the refusal
        but never silently — the returned reveal record carries the honest
        ``quorum`` flag, so a forced reveal is self-documenting evidence of
        defection (B4).  Production callers must not pass it.
        """
        awarded = _as_fraction(awarded_fraction)
        key = (job_id, m)
        rungs = self._rungs.get(key, [])
        if key not in self._rungs and key not in self._fees:
            raise EscrowError("nothing attested for this (job, milestone)")
        count = self._count_quorum(job_id, m, awarded, votes)
        quorum = count >= self.k
        if not quorum and not force:
            raise QuorumNotMet(
                f"{count} valid signed vote(s) for this award, need {self.k}"
            )
        total = sum(v for _r, v, _p in rungs)
        awarded_amount = total * awarded
        if awarded_amount.denominator != 1:
            raise EscrowError(
                "awarded fraction of the rung-set value is not an integer"
            )
        remaining = int(awarded_amount)
        preimages = []
        for r, value, preimage in sorted(rungs, key=lambda t: (-t[1], t[0])):
            if value <= remaining:
                remaining -= value
                preimages.append(
                    {"rung": r, "amount_mc": value, "preimage": b64u_encode(preimage)}
                )
        if remaining:
            raise EscrowError(
                "awarded fraction does not compose exactly from the rung"
                " denominations (§9.3 split-award ladder)"
            )
        fee = self._fees.get(key)
        if fee is not None:
            fee_mc, fee_preimage = fee
            preimages.append(
                {
                    "rung": FEE_RUNG,
                    "amount_mc": fee_mc,
                    "preimage": b64u_encode(fee_preimage),
                }
            )
        return {
            "job_id": job_id,
            "milestone": m,
            "arbiter_id": self.arbiter_id,
            "award_num": awarded.numerator,
            "award_den": awarded.denominator,
            "quorum": quorum,
            "votes": list(votes),
            "preimages": preimages,
        }

    # -- records ---------------------------------------------------------

    def sign_dispute(self, record: dict) -> dict:
        """Sign a §10.2 dispute-outcome record as this arbiter (C12)."""
        from aicash.receipts import sign_dispute

        return sign_dispute(record, self._private, self.arbiter_id)


# ---------------------------------------------------------------------------
# EscrowPayer — funds by-hash locked outputs, refunds at expiry
# ---------------------------------------------------------------------------


class EscrowPayer:
    """The payer side of one §9.3 escrow job.

    Holds the funding tokens, generates one fresh refund secret per
    milestone (requirement 7 — and only the payer ever holds them), funds
    every attested output by hash, and refunds whatever is still unspent
    once a milestone's expiry passes.
    """

    def __init__(
        self,
        client,
        mint_id: str,
        funding_tokens: list[str],
        settlement_margin_ms: int = 60_000,
        arbiter_pubs: dict | None = None,
    ):
        self._client = client
        self._mint_id = mint_id
        self._tokens = list(funding_tokens)
        self._margin = _require_ms("settlement_margin", settlement_margin_ms, 1)
        self._arbiter_pubs = dict(arbiter_pubs) if arbiter_pubs else None
        self._refund_secrets: dict[int, bytes] = {}
        self._funded: list[dict] | None = None
        self._holdings: list[tuple[bytes, int]] = []  # (secret, amount)

    def balance(self) -> int:
        """Plain value held back by the payer (change + refunds), net."""
        return sum(a for _s, a in self._holdings)

    def fund(
        self,
        job_id: str,
        milestones: list[dict],
        attestations: list[dict],
        payee_hashes: dict,
        expiries: dict,
    ) -> FundingInfo:
        """Fund the whole job in one ``/v3/exchange`` call: one by-hash
        locked output per signed attestation, expiries per milestone,
        distinct refund secrets per milestone.

        ``milestones``: ``[{m, evidence_deadline, decision_deadline}, ...]``
        — deadline ordering is enforced HERE, at fund time (requirement 6):
        each ``expiries[m]`` must satisfy ``compute_deadlines``.

        ``payee_hashes``: ``{(m, arbiter_id, rung): secret_hash}`` — rung
        output hashes from the payee, fee output hashes from the panel's
        fee account.  The payer never learns any output secret.

        Structural fee-neutrality assert (requirement 5): any two attested
        outputs sharing a preimage hash — in particular a fee output locked
        to a milestone release preimage — are refused outright.
        """
        if self._funded is not None:
            raise EscrowError("fund() already called for this job")
        desc = self._client.descriptor()
        policy = _policy_from_descriptor(desc)
        grace_ms = desc["lock_params"]["grace_ms"]
        max_batch = desc["limits"]["max_batch"]

        # Requirement 6: deadline ordering enforced at fund time.
        known_m = set()
        for spec in milestones:
            m = spec["m"]
            known_m.add(m)
            if m not in expiries:
                raise DeadlineError(f"no expiry given for milestone {m}")
            min_expiry = compute_deadlines(
                spec["evidence_deadline"],
                spec["decision_deadline"],
                grace_ms,
                self._margin,
            )
            if expiries[m] < min_expiry:
                raise DeadlineError(
                    f"milestone {m} expiry {expiries[m]} is below the"
                    f" conformant minimum {min_expiry}"
                    " (decision_deadline + grace_ms + settlement_margin)"
                )

        # Validate the attestation set.
        seen_hashes: set[str] = set()
        seen_keys: set[tuple] = set()
        records: list[dict] = []
        for a in attestations:
            if not isinstance(a, dict) or a.get("kind") != "attestation":
                raise EscrowError("attestations must be signed attestation dicts")
            m = a["milestone"]
            if m not in known_m:
                raise EscrowError(f"attestation for unknown milestone {m}")
            if self._arbiter_pubs is not None:
                pub = self._arbiter_pubs.get(a["arbiter_id"])
                if pub is None or not verify_obj(a, pub):
                    raise EscrowError(
                        f"attestation signature invalid for milestone {m},"
                        f" arbiter {a.get('arbiter_id')!r}, rung {a.get('rung')}"
                    )
            h = a["preimage_hash"]
            if h in seen_hashes:
                raise EscrowError(
                    "attested preimage hashes must be pairwise distinct — a"
                    " fee output can never be locked to a milestone release"
                    " preimage, and no two rungs may share one (L15/§9.3)"
                )
            seen_hashes.add(h)
            key = _attestation_key(a)
            if key in seen_keys:
                raise EscrowError(f"duplicate attestation for {key}")
            seen_keys.add(key)
            if key not in payee_hashes:
                raise EscrowError(f"no output secret hash supplied for {key}")
            records.append(
                {
                    "milestone": m,
                    "arbiter_id": a["arbiter_id"],
                    "rung": a["rung"],
                    "amount_mc": a["amount_mc"],
                    "secret_hash": payee_hashes[key],
                    "preimage_hash": h,
                    "expiry": expiries[m],
                }
            )

        # Requirement 7: one fresh refund secret per milestone, payer-held.
        for m in sorted(known_m):
            self._refund_secrets[m] = new_secret()

        escrow_total = sum(r["amount_mc"] for r in records)
        input_sum = 0
        for t in self._tokens:
            tok = parse_token(t)
            if tok.mint_id != self._mint_id:
                raise EscrowError("funding token from a different mint")
            input_sum += tok.amount_mc
        burn = compute_burn(input_sum, policy)
        change = input_sum - escrow_total - burn
        if change < 0:
            raise EscrowError(
                f"funding tokens cover {input_sum} mc but the job needs"
                f" {escrow_total} mc + {burn} mc burn"
            )
        outputs = [
            {
                "amount_mc": r["amount_mc"],
                "secret_hash": r["secret_hash"],
                "lock": {
                    "preimage_hash": r["preimage_hash"],
                    "expiry": r["expiry"],
                    "refund_hash": _sha256_b64u(
                        self._refund_secrets[r["milestone"]]
                    ),
                },
            }
            for r in records
        ]
        change_secret = None
        if change > 0:
            change_secret = new_secret()
            outputs.append(
                {
                    "amount_mc": change,
                    "secret_hash": ledger_key(change_secret),
                    "lock": None,
                }
            )
        if len(self._tokens) + len(outputs) > max_batch:
            raise EscrowError(
                "job does not fit in one exchange call (limits.max_batch);"
                " fund per milestone with per-milestone token splits"
            )
        self._client.exchange(str(uuid.uuid4()), list(self._tokens), outputs)
        if change_secret is not None:
            self._holdings.append((change_secret, change))
        self._funded = records
        self._job_id = job_id
        return FundingInfo(
            job_id=job_id,
            mint_id=self._mint_id,
            outputs=tuple(dict(r) for r in records),
            expiries=dict(expiries),
            burn_mc=burn,
            change_mc=change,
        )

    def refund_expired(self, m: int) -> int:
        """Refund every still-unspent output of milestone ``m`` via the
        §3.4 refund path (ledger hash + this milestone's refund secret; no
        token secret — L5).  The mint enforces ``mint_time >= expiry``.
        Returns the net amount recovered (0 when nothing was refundable)."""
        if self._funded is None:
            raise EscrowError("nothing funded")
        if m not in self._refund_secrets:
            raise EscrowError(f"unknown milestone {m}")
        desc = self._client.descriptor()
        policy = _policy_from_descriptor(desc)
        max_batch = desc["limits"]["max_batch"]
        mine = [r for r in self._funded if r["milestone"] == m]
        hashes = [r["secret_hash"] for r in mine]
        results = _status_chunked(self._client, hashes, max_batch)
        unspent = [
            r
            for r, res in zip(mine, results)
            if res.get("state") == "unspent"
        ]
        if not unspent:
            return 0
        witness = b64u_encode(self._refund_secrets[m])
        inputs = [{"hash": r["secret_hash"], "witness": witness} for r in unspent]
        total = sum(r["amount_mc"] for r in unspent)
        burn = compute_burn(total, policy)
        net = total - burn
        fresh = new_secret()
        outputs = (
            [{"amount_mc": net, "secret_hash": ledger_key(fresh), "lock": None}]
            if net > 0
            else []
        )
        self._client.exchange(str(uuid.uuid4()), inputs, outputs)
        if net > 0:
            self._holdings.append((fresh, net))
        return net


