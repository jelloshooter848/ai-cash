def make_dispute_record(
    job_id: str,
    milestone: int,
    claimed_mc: int,
    released_mc: int,
    arbiter_ids: list,
    evidence,
    timestamp: int,
    votes: list,
    refusals=(),
) -> dict:
    """Build the §10.2 dispute-outcome record for an escrow milestone via
    C12: the decision is derived from claimed vs released amounts
    ("released" / "refunded" / "split"), the signed vote set is attached
    as mandatory panel evidence (L15), and party refusals are recorded."""
    if released_mc == claimed_mc:
        decision = "released"
    elif released_mc == 0:
        decision = "refunded"
    else:
        decision = "split"
