def _sha256_b64u(data: bytes) -> str:
    return b64u_encode(hashlib.sha256(data).digest())


def evidence_hash(evidence) -> str:
    """b64u(sha256(canonical_json(evidence))) — what votes bind to (B7)."""
    return _sha256_b64u(canonical_json(evidence))


def _require_ms(name: str, value, minimum: int = 0) -> int:
    if type(value) is not int:
        raise DeadlineError(f"{name} must be a plain integer (ms)")
    if value < minimum:
        raise DeadlineError(f"{name} must be >= {minimum}")
    return value


def compute_deadlines(
    evidence_deadline: int,
    decision_deadline: int,
    grace_ms: int,
    settlement_margin: int,
) -> int:
    """Return the minimum conformant lock expiry ``T_m`` for a milestone.

    Enforces the §9.3 ordering that makes refund-after-delivery impossible:

        evidence_deadline < decision_deadline
        T_m >= decision_deadline + grace_ms + settlement_margin

    A payee who receives the release preimages at the worst allowed moment
    (exactly ``decision_deadline``) still has ``grace_ms +
    settlement_margin`` of mint time before the refund path opens, and its
    claim submission stays outside the §3.4 ``grace_ms`` client convention.
    ``settlement_margin`` must be at least 1 ms — with a zero margin a
    reveal exactly at the decision deadline could land at ``mint_time ==
    expiry``, which belongs to the refund path (R3).  Raises
    ``DeadlineError`` on any ordering that would break the guarantee (B2).
    """
    _require_ms("evidence_deadline", evidence_deadline)
    _require_ms("decision_deadline", decision_deadline)
    _require_ms("grace_ms", grace_ms)
    _require_ms("settlement_margin", settlement_margin, minimum=1)
    if decision_deadline <= evidence_deadline:
        raise DeadlineError(
            "decision_deadline must be strictly after evidence_deadline"
        )
    return decision_deadline + grace_ms + settlement_margin


def rung_composition(total_mc: int, denoms_desc) -> list[int]:
    """§9.6 ladder composition for a rung set, "so fractional awards
    compose cleanly": greedy over the denominations, then one coin of each
    denomination above the smallest is broken into the next rung down.
    E.g. 9,000 over (1000, 100, 10) → 8×1000 + 9×100 + 10×10."""
    denoms = sorted({int(d) for d in denoms_desc}, reverse=True)
    if not denoms or any(d <= 0 for d in denoms):
        raise EscrowError("denominations must be positive integers")
    counts = {}
    remaining = int(total_mc)
    for d in denoms:
        counts[d], remaining = divmod(remaining, d)
    if remaining:
        raise EscrowError(
            f"{total_mc} mc is not representable in denominations {denoms}"
        )
    for i, d in enumerate(denoms[:-1]):
        nxt = denoms[i + 1]
        if d % nxt:
            raise EscrowError("denominations must form a ladder")
        if counts[d] > 0:
            counts[d] -= 1
            counts[nxt] += d // nxt
    out: list[int] = []
    for d in denoms:
        out.extend([d] * counts[d])
    return out


def _as_fraction(value) -> Fraction:
    """Normalize a decision/award to an exact ``Fraction`` in [0, 1].

    Accepts "release" (== 1), "refund" (== 0), an int 0/1, a ``Fraction``,
    or an exact ``(numerator, denominator)`` tuple.  Floats are refused."""
    if value == "release":
        return Fraction(1)
    if value == "refund":
        return Fraction(0)
    if isinstance(value, Fraction):
        f = value
    elif isinstance(value, bool):
        raise EscrowError("decision must not be a bool")
    elif isinstance(value, int):
        f = Fraction(value)
    elif isinstance(value, tuple) and len(value) == 2:
        f = Fraction(value[0], value[1])
    else:
        raise EscrowError(
            'decision must be "release", "refund", a Fraction, or a'
            " (num, den) tuple — floats are refused (no floats, ever)"
        )
    if not (0 <= f <= 1):
        raise EscrowError("award fraction must be within [0, 1]")
    return f


def _policy_from_descriptor(desc: dict) -> BurnPolicy:
    """The burn policy in force per the mint's own clock (never wall time)."""
    bp = desc["burn_policy"]
    current = BurnPolicy(
        rate_ppm=bp["rate_ppm"],
        cap_mc=bp["cap_mc"],
        exempt_below_mc=bp["exempt_below_mc"],
    )
    nxt = desc.get("burn_policy_next")
    next_t = None
    if nxt is not None:
        np = nxt["policy"]
        next_t = (
            BurnPolicy(
                rate_ppm=np["rate_ppm"],
                cap_mc=np["cap_mc"],
                exempt_below_mc=np["exempt_below_mc"],
            ),
            nxt["effective_at"],
        )
    return effective_policy(current, next_t, desc["mint_time"])


def _status_chunked(client, hashes: list[str], max_batch: int) -> list[dict]:
    results: list[dict] = []
    step = max(1, int(max_batch))
    for i in range(0, len(hashes), step):
        _mt, part = client.status(hashes[i : i + step])
        results.extend(part)
    return results


def _attestation_key(a: dict):
    return (a["milestone"], a["arbiter_id"], a["rung"])


