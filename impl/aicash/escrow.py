# CommitThenAccept — §9.4 micro-escrow
# ---------------------------------------------------------------------------


class CommitThenAccept:
    """One §9.4 commit-then-accept session (the sub-5-cent tier).

    One object models the session; the two parties' secrets live in
    strictly separate attributes and are generated by their own methods
    (L15): the worker's output secret in ``worker_hash``, the payer's
    acceptance preimage and refund secret in ``payer_commit``.  The funds
    are non-retractable until expiry even though the payer knows the
    preimage — it lacks the worker's output secret (§3.4, R1).

    Reveal deadline (requirement 6): ``payer_reveal`` refuses past
    ``expiry − grace_ms − redemption_margin`` — measured against the
    MINT's clock, never wall time — records the refusal, and raises
    ``LateReveal``; §10.2 treats it as a payer refusal.
    """

    def __init__(
        self,
        client,
        mint_id: str,
        redemption_margin_ms: int = 60_000,
        grace_ms: int | None = None,
    ):
        self._client = client
        self._mint_id = mint_id
        self._margin = _require_ms("redemption_margin", redemption_margin_ms, 1)
        self._grace_override = grace_ms
        # worker side
        self._worker_secret: bytes | None = None
        # payer side
        self._preimage: bytes | None = None
        self._refund_secret: bytes | None = None
        self._payer_holdings: list[tuple[bytes, int]] = []
        # agreed terms (set at commit)
        self.secret_hash: str | None = None
        self.amount_mc: int | None = None
        self.expiry: int | None = None
        self._grace_ms: int | None = None
        #: recorded refusals (late reveals) — §10.2 evidence (B6)
        self.refusals: list[dict] = []

    # -- worker side -----------------------------------------------------

    def worker_hash(self) -> str:
        """The worker generates and holds its fresh output secret; the
        payer only ever sees the hash (by-hash funding, §3.3)."""
        if self._worker_secret is not None:
            raise EscrowError("worker secret already generated")
        self._worker_secret = new_secret()
        return ledger_key(self._worker_secret)

    def worker_verify(self, amount_mc: int | None = None, expiry: int | None = None) -> None:
        """MANDATORY before working (§9.4): confirm the committed funds on
        the ledger — present, unspent, agreed amount, agreed expiry,
        locked.  Raises ``FundingInvalid`` otherwise (B6)."""
        if self._worker_secret is None:
            raise EscrowError("call worker_hash() first")
        amount = amount_mc if amount_mc is not None else self.amount_mc
        expected_expiry = expiry if expiry is not None else self.expiry
        if amount is None or expected_expiry is None:
            raise EscrowError("agreed amount/expiry unknown")
        h = ledger_key(self._worker_secret)
        _mt, results = self._client.status([h])
        res = results[0]
        if res.get("state") == "unknown":
            raise FundingInvalid("committed funds absent from the ledger")
        if res.get("state") != "unspent":
            raise FundingInvalid("committed output already spent")
        if res.get("amount_mc") != amount:
            raise FundingInvalid("committed amount differs from the agreement")
        lock = res.get("lock")
        if not isinstance(lock, dict):
            raise FundingInvalid("committed output is not locked")
        if lock.get("expiry") != expected_expiry:
            raise FundingInvalid("committed expiry differs from the agreement")

    def worker_redeem(self, preimage_b64u: str) -> int:
        """Claim with the worker's own secret + the revealed preimage,
        strictly before expiry (the mint enforces).  Returns the net."""
        if self._worker_secret is None or self.amount_mc is None:
            raise EscrowError("nothing committed")
        preimage = b64u_decode(preimage_b64u, expect_len=32)
        desc = self._client.descriptor()
        policy = _policy_from_descriptor(desc)
        burn = compute_burn(self.amount_mc, policy)
        net = self.amount_mc - burn
        fresh = new_secret()
        inputs = [
            {
                "token": format_token(
                    self._mint_id, self.amount_mc, self._worker_secret
                ),
                "witness": b64u_encode(preimage),
            }
        ]
        outputs = (
            [{"amount_mc": net, "secret_hash": ledger_key(fresh), "lock": None}]
            if net > 0
            else []
        )
        self._client.exchange(str(uuid.uuid4()), inputs, outputs)
        return net

    # -- payer side ------------------------------------------------------

    def payer_commit(
        self,
        hash_from_worker: str,
        amount_mc: int,
        expiry: int,
        funding_tokens: list[str],
    ) -> None:
        """Fund a by-hash output at the worker's hash, locked to the
        payer's OWN fresh acceptance preimage with a short expiry (§9.4)."""
        if self._preimage is not None:
            raise EscrowError("already committed")
        if type(amount_mc) is not int or amount_mc <= 0:
            raise EscrowError("amount_mc must be a positive integer")
        _require_ms("expiry", expiry, 1)
        desc = self._client.descriptor()
        policy = _policy_from_descriptor(desc)
        grace = (
            self._grace_override
            if self._grace_override is not None
            else desc["lock_params"]["grace_ms"]
        )
        self._preimage = new_secret()
        self._refund_secret = new_secret()
        input_sum = 0
        for t in funding_tokens:
            tok = parse_token(t)
            if tok.mint_id != self._mint_id:
                raise EscrowError("funding token from a different mint")
            input_sum += tok.amount_mc
        burn = compute_burn(input_sum, policy)
        change = input_sum - amount_mc - burn
        if change < 0:
            raise EscrowError("funding tokens do not cover amount + burn")
        outputs = [
            {
                "amount_mc": amount_mc,
                "secret_hash": hash_from_worker,
                "lock": {
                    "preimage_hash": _sha256_b64u(self._preimage),
                    "expiry": expiry,
                    "refund_hash": _sha256_b64u(self._refund_secret),
                },
            }
        ]
        change_secret = None
        if change > 0:
            change_secret = new_secret()
            outputs.append(
                {
                    "amount_mc": change,
                    "secret_hash": ledger_key(change_secret),
                    "lock": None,
                }
            )
        self._client.exchange(str(uuid.uuid4()), list(funding_tokens), outputs)
        if change_secret is not None:
            self._payer_holdings.append((change_secret, change))
        self.secret_hash = hash_from_worker
        self.amount_mc = amount_mc
        self.expiry = expiry
        self._grace_ms = grace

    def reveal_deadline(self) -> int:
        """§9.4: ``expiry − grace_ms − redemption_margin``."""
        if self.expiry is None or self._grace_ms is None:
            raise EscrowError("nothing committed")
        return self.expiry - self._grace_ms - self._margin

    def payer_reveal(self) -> str:
        """Reveal acceptance: return the preimage — but ONLY up to the
        reveal deadline (checked against the mint clock).  A later reveal
        would trap the worker against the §3.4 grace convention, so it
        raises ``LateReveal`` and is recorded as a refusal (§10.2)."""
        if self._preimage is None:
            raise EscrowError("nothing committed")
        deadline = self.reveal_deadline()
        mint_time, _results = self._client.status([])
        if mint_time > deadline:
            refusal = {
                "kind": "late_reveal",
                "party": "payer",
                "secret_hash": self.secret_hash,
                "mint_time": mint_time,
                "reveal_deadline": deadline,
                "expiry": self.expiry,
            }
            self.refusals.append(refusal)
            raise LateReveal(
                f"reveal at mint_time {mint_time} is past the deadline"
                f" {deadline} (expiry − grace_ms − redemption_margin);"
                " recorded as a payer refusal (§9.4/§10.2)"
            )
        return b64u_encode(self._preimage)

    def payer_refund(self) -> int:
        """Refund path at/after expiry (mint-enforced).  Returns the net."""
        if self._refund_secret is None or self.amount_mc is None:
            raise EscrowError("nothing committed")
        desc = self._client.descriptor()
        policy = _policy_from_descriptor(desc)
        burn = compute_burn(self.amount_mc, policy)
        net = self.amount_mc - burn
        fresh = new_secret()
        inputs = [
            {
                "hash": self.secret_hash,
                "witness": b64u_encode(self._refund_secret),
            }
        ]
        outputs = (
            [{"amount_mc": net, "secret_hash": ledger_key(fresh), "lock": None}]
            if net > 0
            else []
        )
        self._client.exchange(str(uuid.uuid4()), inputs, outputs)
        if net > 0:
            self._payer_holdings.append((fresh, net))
        return net


