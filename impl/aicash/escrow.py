"""C09 — escrow: the Conditional Work Exchange conventions (spec §9.3, §9.4, §9.6).

Single-arbiter milestones, the k-of-n rung construction with signed votes,
split awards, decision-neutral fees, deadline arithmetic, and
commit-then-accept — all built from the unmodified §3.4 lock primitive
against an ordinary C06 mint.  Locked decision L15 applies throughout.

No joint secrets anywhere (L15 — grep-level review point):
every 32-byte preimage in this module is generated by ``new_secret()`` in
exactly one place and held by exactly one party:

  * rung preimages ``a_{j,m,r}``   — ``Arbiter.attest_rungs`` (arbiter j only)
  * fee preimages ``f_{j,m}``      — ``Arbiter.attest_rungs`` (arbiter j only)
  * refund secrets ``r_m``         — ``EscrowPayer.fund`` (payer only,
                                     one fresh secret per milestone — req 7)
  * payee/fee-account output secrets — ``EscrowPayee.generate_output_hashes``
                                     (that holder only)
  * §9.4 acceptance preimage + refund secret — ``CommitThenAccept.payer_commit``
                                     (payer only)
  * §9.4 worker output secret      — ``CommitThenAccept.worker_hash``
                                     (worker only)

Nothing is ever derived from, split out of, or shared between these; the
quorum rule is a signed-vote convention among arbiters (R10), and any
defection from it is bounded to value/n and provable against the
defector's signed vote.

Decision-neutral fees (requirement 5, asserted structurally): a fee
attestation's preimage is generated independently of every rung preimage,
``EscrowPayer.fund`` refuses any attestation set in which two attested
outputs share a preimage hash (so a fee output locked to a milestone
release preimage is impossible through this API), and
``EscrowPayee.verify_funding`` re-checks the same disjointness.

Time discipline (L17): this module never reads wall time.  The only
temporal check performed client-side — the §9.4 reveal deadline — uses
``mint_time`` as reported by the mint's own ``/v3/status`` response.
Everything else is deadline *arithmetic* (no clock) or is enforced by the
mint's commit-time lock evaluation.

Fractions: awards travel as exact integer ratios (``award_num`` /
``award_den``).  Floats are refused ("no floats, ever" — §3.1 ethos and
§3.3 canonical JSON).
"""

