# EscrowPayee — output-secret holder: MANDATORY funding verification, redeem
# ---------------------------------------------------------------------------


class EscrowPayee:
    """The output-secret-holding side of one escrow job: the payee proper
    (rung outputs) or the panel's fee account (fee outputs — pass
    ``kinds=("fee",)`` to ``generate_output_hashes``)."""

    def __init__(self, client, mint_id: str, arbiter_pubs: dict):
        self._client = client
        self._mint_id = mint_id
        self._arbiter_pubs = dict(arbiter_pubs)
        self._secrets: dict[tuple, bytes] = {}  # (m, arbiter_id, rung) -> secret
        self._pinned: dict[tuple, dict] = {}
        self._verified = False
        self._holdings: list[tuple[bytes, int]] = []

    def balance(self) -> int:
        return sum(a for _s, a in self._holdings)

    def generate_output_hashes(self, attestations, kinds=("rung",)) -> dict:
        """Generate one fresh output secret per attested output of the
        given kinds and return ``{(m, arbiter_id, rung): secret_hash}`` for
        the payer's by-hash funding call.  Only this instance ever holds
        the secrets."""
        out = {}
        for a in attestations:
            kind = FEE_RUNG if a["rung"] == FEE_RUNG else "rung"
            if kind not in kinds:
                continue
            key = _attestation_key(a)
            if key in self._secrets:
                raise EscrowError(f"output secret already generated for {key}")
            secret = new_secret()
            self._secrets[key] = secret
            out[key] = ledger_key(secret)
        return out

    def verify_funding(self, info: FundingInfo | dict, attestations) -> None:
        """The MANDATORY §9.3 pre-work check (requirement 2), complete.

        ``info`` is the payer's handoff: a FundingInfo, or its wire form —
        the ``FundingInfo.to_dict`` canonical-JSON-safe dict as received
        from a stranger payer across a process boundary (parsed via
        ``FundingInfo.from_dict``; a malformed wire dict raises
        ``EscrowError``).

        The checks:

        * every attestation signature verifies against its arbiter's key;
        * attested preimage hashes are pairwise distinct (fee/rung
          disjointness re-checked);
        * the funded output set matches the attested set exactly;
        * every output we hold a secret for is keyed by OUR hash;
        * on the ledger (batch ``/v3/status``): every output exists, is
          unspent, has the attested amount, the agreed expiry, and a lock
          whose ``preimage_hash`` equals the attested value.

        Any failure raises ``FundingInvalid`` naming the offending rung.
        Without this check a payer can fund locks keyed to a preimage of
        its own invention and silently reconstruct refund-after-delivery
        (§9.3, B3).  Nothing is pinned unless every check passes.
        """
        if isinstance(info, dict):
            info = FundingInfo.from_dict(info)
        if not isinstance(info, FundingInfo):
            raise EscrowError("info must be a FundingInfo or its wire dict")
        atts: dict[tuple, dict] = {}
        seen_hashes: set[str] = set()
        for a in attestations:
            key = _attestation_key(a)
            m, arb, rung = key
            pub = self._arbiter_pubs.get(arb)
            if pub is None:
                raise FundingInvalid("attesting arbiter unknown", m, arb, rung)
            if not verify_obj(a, pub):
                raise FundingInvalid("attestation signature invalid", m, arb, rung)
            if a.get("job_id") != info.job_id:
                raise FundingInvalid("attestation for a different job", m, arb, rung)
            if key in atts:
                raise FundingInvalid("duplicate attestation", m, arb, rung)
            if a["preimage_hash"] in seen_hashes:
                raise FundingInvalid(
                    "attested preimage hash reused — fee and rung locks must"
                    " be pairwise distinct (L15/§9.3)",
                    m,
                    arb,
                    rung,
                )
            seen_hashes.add(a["preimage_hash"])
            atts[key] = a

        outs: dict[tuple, dict] = {}
        for o in info.outputs:
            key = (o["milestone"], o["arbiter_id"], o["rung"])
            if key in outs:
                raise FundingInvalid("duplicate funded output", *key)
            outs[key] = o
        for key in atts:
            if key not in outs:
                raise FundingInvalid("attested output missing from funding", *key)
        for key in outs:
            if key not in atts:
                raise FundingInvalid("funded output has no attestation", *key)

        # Deterministic order (rung keys mix ints and the "fee" marker).
        def _order(key):
            m, arb, rung = key
            is_fee = rung == FEE_RUNG
            return (m, arb, is_fee, rung if isinstance(rung, int) else -1)

        ordered = sorted(outs, key=_order)
        for key in ordered:
            o, a = outs[key], atts[key]
            if o["amount_mc"] != a["amount_mc"]:
                raise FundingInvalid("amount differs from attestation", *key)
            if o["preimage_hash"] != a["preimage_hash"]:
                raise FundingInvalid(
                    "claimed lock hash differs from attestation", *key
                )
            if o["expiry"] != info.expiries[key[0]]:
                raise FundingInvalid("expiry differs from the schedule", *key)
            secret = self._secrets.get(key)
            if secret is not None and o["secret_hash"] != ledger_key(secret):
                raise FundingInvalid(
                    "output not keyed to our secret hash", *key
                )

        desc = self._client.descriptor()
        max_batch = desc["limits"]["max_batch"]
        hashes = [outs[key]["secret_hash"] for key in ordered]
        results = _status_chunked(self._client, hashes, max_batch)
        pinned: dict[tuple, dict] = {}
        for key, res in zip(ordered, results):
            o = outs[key]
            state = res.get("state")
            if state == "unknown":
                raise FundingInvalid("output not on the ledger", *key)
            if state != "unspent":
                raise FundingInvalid("output already spent", *key)
            if res.get("amount_mc") != o["amount_mc"]:
                raise FundingInvalid("on-ledger amount mismatch", *key)
            lock = res.get("lock")
            if not isinstance(lock, dict):
                raise FundingInvalid("output is not locked", *key)
            if lock.get("preimage_hash") != atts[key]["preimage_hash"]:
                raise FundingInvalid(
                    "funded lock hash does not equal the arbiter-attested"
                    " preimage hash",
                    *key,
                )
            if lock.get("expiry") != info.expiries[key[0]]:
                raise FundingInvalid("on-ledger expiry mismatch", *key)
            pinned[key] = {
                "amount_mc": o["amount_mc"],
                "secret_hash": o["secret_hash"],
                "preimage_hash": atts[key]["preimage_hash"],
                "expiry": o["expiry"],
            }
        # Pin only after EVERY check passed.
        self._pinned = pinned
        self._verified = True

    def redeem(self, m: int, reveals, allow_unverified: bool = False) -> int:
        """Claim every revealed output of milestone ``m`` that this
        instance holds a secret for, in ONE ``/v3/exchange`` call (one
        burn).  Each revealed preimage is checked against the PINNED
        (verified) lock hash before anything goes on the wire; a mismatch
        raises ``RevealInvalid`` naming the rung.

        Redeeming without a prior successful ``verify_funding`` is refused
        (the §9.3 check is mandatory); ``allow_unverified=True`` exists
        solely to model a negligent payee in tests (B3's sandboxed
        demonstration) and submits the reveals unchecked — the mint then
        adjudicates."""
        if not self._verified and not allow_unverified:
            raise EscrowError(
                "funding not verified — §9.3 mandates verify_funding before"
                " any work or redemption"
            )
        entries = []
        seen: set[tuple] = set()
        for r in reveals:
            if r.get("milestone") != m:
                continue
            arb = r.get("arbiter_id")
            for e in r.get("preimages", []):
                key = (m, arb, e["rung"])
                if key in seen:
                    continue
                secret = self._secrets.get(key)
                if secret is None:
                    continue
                preimage = b64u_decode(e["preimage"], expect_len=32)
                if self._verified:
                    pin = self._pinned.get(key)
                    if pin is None:
                        continue  # not part of the verified funding
                    if _sha256_b64u(preimage) != pin["preimage_hash"]:
                        raise RevealInvalid(
                            f"revealed preimage for milestone {m}, arbiter"
                            f" {arb!r}, rung {e['rung']} does not open the"
                            " verified funded lock"
                        )
                    amount = pin["amount_mc"]
                else:
                    amount = e["amount_mc"]
                seen.add(key)
                entries.append((key, secret, amount, preimage))
        if not entries:
            return 0
        desc = self._client.descriptor()
        policy = _policy_from_descriptor(desc)
        inputs = [
            {
                "token": format_token(self._mint_id, amount, secret),
                "witness": b64u_encode(preimage),
            }
            for _key, secret, amount, preimage in entries
        ]
        total = sum(amount for _k, _s, amount, _p in entries)
        burn = compute_burn(total, policy)
        net = total - burn
        fresh = new_secret()
        outputs = (
            [{"amount_mc": net, "secret_hash": ledger_key(fresh), "lock": None}]
            if net > 0
            else []
        )
        self._client.exchange(str(uuid.uuid4()), inputs, outputs)
        for key, _s, _a, _p in entries:
            self._secrets.pop(key, None)  # settled: the entry is spent
        if net > 0:
            self._holdings.append((fresh, net))
        return net


