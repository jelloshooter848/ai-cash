class EscrowError(Exception):
    """Base class for every §9.3/§9.4 convention violation."""


class DeadlineError(EscrowError):
    """Deadline ordering that would re-enable refund-after-delivery."""


class FundingInvalid(EscrowError):
    """§9.3 mandatory funding verification failed.  The message and the
    ``milestone`` / ``arbiter_id`` / ``rung`` / ``reason`` attributes name
    the offending output (requirement 2)."""

    def __init__(self, reason: str, milestone=None, arbiter_id=None, rung=None):
        self.reason = reason
        self.milestone = milestone
        self.arbiter_id = arbiter_id
        self.rung = rung
        where = ""
        if milestone is not None:
            where = f" at milestone {milestone}, arbiter {arbiter_id!r}, rung {rung}"
        super().__init__(f"funding invalid{where}: {reason}")


class QuorumNotMet(EscrowError):
    """``Arbiter.reveal`` refused: fewer than k valid signed votes for this
    (job, milestone, evidence, award) were supplied (requirement 3)."""


class RevealInvalid(EscrowError):
    """A revealed preimage does not open the verified funded lock."""


class LateReveal(EscrowError):
    """§9.4: the payer tried to reveal after ``expiry − grace − margin``;
    the attempt is recorded as a refusal (requirement 6)."""


